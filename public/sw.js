/* /infographic/ service worker (v3.10.0) — instant repeat visits and offline use for "Land changing hands".
   Pages under this scope (the page and title-chain/) are answered from a versioned cache at once and revalidated in the
   background with a conditional request (the browser sends If-None-Match / If-Modified-Since where the server gave them);
   when the fresh copy carries a different build, open tabs are told and show a small "tap to refresh" button.
   The site's own worker is loaded below, so audio, JSON and images the site serves from its catalogue database are answered
   exactly as on every other page. Generated by tools/build.py from tools/sw.js — edit that file, not public/sw.js.
   Build: 3.10.0+0a84cb91a7 — Sion's Tab agent */
var BUILD = '3.10.0+0a84cb91a7', CACHE = 'ig-shell-' + BUILD;
var SCOPE = new URL(self.registration.scope).pathname;            // e.g. /infographic/
var PAGES = [SCOPE, SCOPE + 'title-chain/'];
function key(u) { var p = u.pathname.replace(/index\.html$/, ''); return u.origin + p; }
function isPage(req, u) {
  if (req.method !== 'GET' || u.origin !== self.location.origin || u.pathname.indexOf(SCOPE) !== 0) return false;
  return req.mode === 'navigate' || PAGES.indexOf(u.pathname.replace(/index\.html$/, '')) >= 0;
}
function buildOf(text) { var m = /<meta name="ig-build" content="([^"]*)"/.exec(text || ''); return m ? m[1] : ''; }
function fresh(u) {           // plain GET to the clean page address; 'no-cache' = revalidate with the server, never a stale HTTP copy
  return fetch(u.origin + u.pathname.replace(/index\.html$/, '') + u.search, { cache: 'no-cache', credentials: 'same-origin' })
    .then(function (r) {
      if (!r.ok || (r.headers.get('content-type') || '').indexOf('text/html') < 0) return null;
      return r.text().then(function (t) {
        return { text: t, headers: { 'Content-Type': r.headers.get('content-type') || 'text/html; charset=utf-8' } };
      });
    }).catch(function () { return null; });
}
function store(u, f) {
  return caches.open(CACHE).then(function (c) {
    return c.put(key(u), new Response(f.text, { headers: f.headers }));
  });
}
function tell(build) {           // every open tab of this app (the one just opened may still be loading: ask again a few times)
  var n = 0;
  function go() {
    return self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then(function (cs) {
      cs.forEach(function (c) { if (c.url.indexOf(self.registration.scope) === 0) c.postMessage({ type: 'ig-updated', build: build }); });
      if (++n < 4) return new Promise(function (z) { setTimeout(z, 1200); }).then(go);
    });
  }
  return go();
}
self.addEventListener('install', function (e) {
  e.waitUntil(Promise.all(PAGES.map(function (p) {
    var u = new URL(p, self.location.origin);
    return fresh(u).then(function (f) { return f && store(u, f); });
  })).catch(function () {}));
});
self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (ks) {
    return Promise.all(ks.filter(function (k) { return k.indexOf('ig-shell-') === 0 && k !== CACHE; }).map(function (k) { return caches.delete(k); }));
  }));
});
self.addEventListener('fetch', function (e) {
  var req = e.request, u;
  try { u = new URL(req.url); } catch (x) { return; }
  if (!isPage(req, u)) return;                                    // everything else: the site's worker below, or the network
  var net = fresh(u);
  e.respondWith(caches.open(CACHE).then(function (c) { return c.match(key(u)); }).then(function (hit) {
    var old = hit ? hit.clone().text() : Promise.resolve('');      // read the cached copy before it is handed to the page
    var update = net.then(function (f) {
      if (!f) return;
      return old.then(function (old) {
        return store(u, f).then(function () { if (hit && buildOf(old) !== buildOf(f.text)) return tell(buildOf(f.text)); });
      });
    });
    e.waitUntil(update.catch(function () {}));
    if (hit) return hit;
    return net.then(function (f) {
      return f ? new Response(f.text, { headers: f.headers }) : fetch(req);
    });
  }));
});
// The site's own worker (catalogue database for audio/JSON/images). Loaded after the listener above so pages are ours.
